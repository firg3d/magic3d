export type CheieTermo = keyof Texte;

export function tt(cheie: CheieTermo, valori: Record<string, string | number> = {}, limba: string = getLanguage()): string {
  const texte = limba === "ro" ? RO : EN;
  return texte[cheie].replace(/\{(\w+)\}/g, (tot, nume: string) => (nume in valori ? String(valori[nume]) : tot));
}
